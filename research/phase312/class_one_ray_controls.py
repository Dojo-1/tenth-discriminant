#!/usr/bin/env python3
"""Phase312 class-one specificity controls for quadratic Fermat moments.

D43 and D163 are class-number-one; D183 is class-number-eight.
All have IDENTICAL mod5 omega-residue polynomial, and all are inert5.
Their matched norm-ball residue/lift moments are finite local data, not
a logical consequence of class number one. Ray class cardinalities use
the CLASSICAL global exact sequence, which is imported, not proved here.
"""
from collections import defaultdict
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[2]
for p in ("phase308","phase311","phase312"):
    sys.path.insert(0,str(ROOT/"research"/p))
from adaptive_torsion_family import independent_reduced_forms
from inert_trace_radicals import full_omega_q
from residue_multiplicity import compressed_original_gram
from fermat_lift import (check_field,epsilon,mul,add,conjugate,
                         field_inverse,transport_controls)

FIELDS=((43,1),(163,1),(183,8))
P=5
MATCHED_RHO=21
MATCHED_ROWS=40


def norm(z,D):
    a,b=z
    m=(D+1)//4
    return a*a+a*b+m*b*b


def moment_census(q,D):
    groups=defaultdict(list)
    for z in q:
        groups[(z[0]%5,z[1]%5)].append(z)
    result={}
    for residue,points in sorted(groups.items()):
        eps=[epsilon(z,D) for z in points]
        total=(0,0)
        square=(0,0)
        hermitian=(0,0)
        for x in eps:
            total=add(total,x,5)
            square=add(square,mul(x,x,D,5),5)
            hermitian=add(hermitian,mul(x,conjugate(x),D,5),5)
        assert hermitian[1]%5==0
        result[residue]={
            "n":len(points),
            "m_mod5":len(points)%5,
            "sum_eps":total,
            "sum_eps_squared":square,
            "sum_eps_norm":hermitian[0],
        }
    # Actual conjugation invariance forces moment relations irrespective
    # of class number, a deliberately universal rather than h1 signal.
    for z,v in result.items():
        zbar=conjugate(z,5)
        w=result[zbar]
        assert w["n"]==v["n"]
        assert w["sum_eps"]==conjugate(v["sum_eps"],5)
        assert w["sum_eps_squared"]==conjugate(v["sum_eps_squared"],5)
        assert w["sum_eps_norm"]==v["sum_eps_norm"]
    return result


def finite_residue_unit_counts(D):
    check_field(D)
    units_mod5=sum(
        norm((a,b),D)%5!=0
        for a in range(5) for b in range(5))
    units_mod25=sum(
        norm((a,b),D)%5!=0
        for a in range(25) for b in range(25))
    assert units_mod5==24 and units_mod25==600
    # For D>3, global units in O_D are ±1. Under the classical
    # ray-class exact sequence, the kernel has size 24/2 or 600/2.
    return units_mod5,units_mod25


def matched_field_controls():
    records=[]
    payload={}
    for D,h in FIELDS:
        check_field(D)
        assert (D+1)//4%5==1
        forms=independent_reduced_forms(D)
        assert len(forms)==h,(D,len(forms),h)
        if D==183:
            assert D==3*61 and not any(x*x==3 for x in range(4))
            assert (D+1)//4>3
            # Ideal of norm3 exists (3 ramifies) but cannot be
            # generated by element of norm3; hence h is not1.
        q=full_omega_q(D,MATCHED_RHO)
        assert len(q)==len(set(q))
        assert all(norm(z,D)<=MATCHED_RHO**2 for z in q)
        G,gram=compressed_original_gram(
            q,D,MATCHED_ROWS,1,1)
        assert gram["observed_distinct_F25_residue_classes"]==25
        assert gram["full_original_residue_jet_span"]
        assert gram["surjective_weighted_pullback_rank_exact_if_applicable"]
        moments=moment_census(q,D)
        n5,n25=finite_residue_unit_counts(D)
        record={
            "D":D,
            "class_number_from_standard_reduced_forms":h,
            "matched_radius_not_native_field_policy":MATCHED_RHO,
            "quadratic_parameter_m":(D+1)//4,
            "omega_residue_polynomial_m_mod5":1,
            "matched_actual_norm_ball_size":len(q),
            "nonzero_mod5_residue_weights":
                gram["nonzero_mod5_multiplicity_classes"],
            "matched_original_40row_Gram_rank_F5":
                gram["original_Gram_rank_F5"],
            "exact_census_sum_eps_mod5":
                [sum(v["sum_eps"][i] for v in moments.values())%5
                 for i in (0,1)],
            "exact_census_sum_eps_squared_mod5":
                [sum(v["sum_eps_squared"][i] for v in moments.values())%5
                 for i in (0,1)],
            "exact_census_sum_eps_norm_mod5":
                sum(v["sum_eps_norm"] for v in moments.values())%5,
            "local_mod5_unit_count":n5,
            "local_mod25_unit_count":n25,
            "ray_class_5_order_conditional_on_standard_exact_sequence":
                h*n5//2,
            "ray_class_25_order_conditional_on_standard_exact_sequence":
                h*n25//2,
            "residue_moment_record_is_not_class_number_one_theorem":True
        }
        payload[D]=(q,moments,record)
        records.append(record)

    assert [x["class_number_from_standard_reduced_forms"] for x in records]==[1,1,8]
    assert [x["ray_class_5_order_conditional_on_standard_exact_sequence"]
            for x in records]==[12,12,96]
    assert [x["ray_class_25_order_conditional_on_standard_exact_sequence"]
            for x in records]==[300,300,2400]
    # Even two h1 fields with identical local residue polynomial have
    # different bounded-norm observation spaces. The local ring alone
    # cannot determine those global radius-truncated subsets.
    assert len(payload[43][0])!=len(payload[163][0])
    # Moving-frame corrected maps at conductor25 compare local arithmetic
    # across fields; they do not map one N<=rho^2 norm-ball to another.
    transports=[
        transport_controls(43,163),transport_controls(163,183),
        transport_controls(43,183)
    ]
    return {
      "matched_fields":records,
      "matched_field_classification_provenance":
          "complete reduced positive primitive forms and classical correspondence",
      "local_Hensel_ring_transports":transports,
      "same_mod5_local_algebra_does_not_classify_global_h1":True,
      "conjugation_moment_relations_are_universal_not_class_one_specific":True,
      "ray_class_order_uses_imported_global_exact_sequence":True,
      "no_congruence_for_bounded_Hecke_sums_proved":True,
      "no_original_field_bound_changed":True
    }


