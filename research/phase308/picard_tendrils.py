from dataclasses import dataclass
from itertools import combinations
from math import gcd, isqrt


class InvalidTransport(ValueError):
    pass


def order_parameter(d):
    if d <= 0 or d % 4 != 3:
        raise InvalidTransport("imaginary quadratic D=3 mod4 required")
    if any(d % (n*n) == 0 for n in range(2, isqrt(d)+1)):
        raise InvalidTransport("D must be squarefree for maximal order")
    return (d+1)//4


def mul(x, y, d=203):
    """(a+b omega)(c+e omega), omega^2=omega-(D+1)/4."""
    m=order_parameter(d)
    a,b=x
    c,e=y
    return (a*c-m*b*e, a*e+b*c+b*e)


def norm(x, d=203):
    a,b=x
    return a*a+a*b+order_parameter(d)*b*b


def conjugate(x):
    a,b=x
    return a+b,-b


def power(x,k,d=203):
    if k<0:
        raise InvalidTransport("negative integral power")
    value=(1,0)
    for _ in range(k):
        value=mul(value,x,d)
    return value


def scalar(x,n):
    return x[0]*n,x[1]*n


def ideal_power_generators(d,p,k):
    """O-module generators for I^k with I=(p,omega) at root zero mod p."""
    if k<0 or p<2:
        raise InvalidTransport("invalid ideal exponent or prime")
    omega=(0,1)
    return [scalar(power(omega,j,d),p**(k-j))
            for j in range(k+1)]


def determinant(v,w):
    return v[0]*w[1]-v[1]*w[0]


def ideal_z_index(d, generators):
    """Independent Z-lattice index via gcd of 2x2 minors.

    Each O-ideal generated by g_j is the Z-span of g_j and omega*g_j.
    For a rank-2 Z sublattice its index is the gcd of all maximal minors.
    """
    expanded=[]
    for g in generators:
        expanded.append(g)
        expanded.append(mul(g,(0,1),d))
    dmin=0
    for v,w in combinations(expanded,2):
        dmin=gcd(dmin,abs(determinant(v,w)))
    if dmin<=0:
        raise InvalidTransport("ideal generators have rank < 2")
    return dmin


def divide_by_element_integrally(g,alpha,d=203):
    """Return quotient in O iff both exact integer coordinates exist."""
    n=norm(alpha,d)
    if n==0:
        raise InvalidTransport("zero divisor in fraction field")
    numerator=mul(g,conjugate(alpha),d)
    if any(v % n for v in numerator):
        raise InvalidTransport("not divisible in integral O")
    return (numerator[0]//n,numerator[1]//n)


def defining_polynomial(t,d):
    return t*t-t+order_parameter(d)


@dataclass(frozen=True)
class HenselWorldlet:
    field_d: int
    prime: int
    level: int
    root: int

    def __post_init__(self):
        if self.level<1 or self.prime<2:
            raise InvalidTransport("bad finite precision")
        if not 0<=self.root<self.prime**self.level:
            raise InvalidTransport("noncanonical Hensel root")
        if defining_polynomial(self.root,self.field_d)%(self.prime**self.level):
            raise InvalidTransport("root is not a lift of ring relation")

    def residue(self,element):
        return (element[0]+self.root*element[1])%(self.prime**self.level)

    def reduce(self,k):
        if not 1<=k<=self.level:
            raise InvalidTransport("precision may only be forgotten")
        return HenselWorldlet(self.field_d,self.prime,k,
                             self.root%(self.prime**k))

    def lift_one(self):
        """One step via unramified Hensel; no magic oracle."""
        p=self.prime
        if (2*self.root-1)%p==0:
            raise InvalidTransport("ramified/ambiguous root; this lift requires simplicity")
        mod=p**(self.level+1)
        options=[self.root+t*p**self.level for t in range(p)
                 if defining_polynomial(self.root+t*p**self.level,self.field_d)%mod==0]
        if len(options)!=1:
            raise InvalidTransport("nonunique Hensel lift")
        return HenselWorldlet(self.field_d,p,self.level+1,options[0])


def hensel_tower(d,p,r0,kmax):
    x=HenselWorldlet(d,p,1,r0)
    out=[x]
    for _ in range(1,kmax):
        x=x.lift_one()
        out.append(x)
    assert all(out[k].reduce(k)==out[k-1] for k in range(1,len(out)))
    return out


def ideal_power_hensel_certificate(d,p,root0,kmax):
    towers=hensel_tower(d,p,root0,kmax)
    for x in towers:
        gens=ideal_power_generators(d,p,x.level)
        assert ideal_z_index(d,gens)==p**x.level
        # Inclusion I^k subset of kernel psi_k, equal finite indices.
        assert all(x.residue(g)==0 for g in gens)
    return towers


