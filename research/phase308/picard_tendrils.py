def reduced_positive_forms(d):
    """Classical reduced primitive forms of discriminant -D, finite census."""
    order_parameter(d)
    out=[]
    maxa=isqrt(d//3)+1
    for a in range(1,maxa+1):
        for b in range(-a,a+1):
            if (b*b+d)%(4*a):
                continue
            c=(b*b+d)//(4*a)
            if a>c or (abs(b)==a or a==c) and b<0:
                continue
            if gcd(gcd(a,abs(b)),c)!=1:
                continue
            out.append((a,b,c))
    return tuple(out)


@dataclass(frozen=True)
class PicardTendril:
    """Actual two-open arithmetic localization cover (not a finite point cover)."""
    d:int
    p:int

    def __post_init__(self):
        m=order_parameter(self.d)
        if m%self.p:
            raise InvalidTransport("this two-chart certificate requires p | m")
        if defining_polynomial(0,self.d)%self.p or defining_polynomial(1,self.d)%self.p:
            raise InvalidTransport("f(0)=f(1)=0 mod p required")
        if self.p<2:
            raise InvalidTransport("invalid prime")

    @property
    def transition(self):
        # I|D(omega)=O, I|D(omega-1)=p O; t=g_V/g_U=p
        return self.p

    def overlap_inverse_numerator(self):
        # 1/p=-(m/p)/(omega*(omega-1)), valid ONLY on overlap.
        return -(order_parameter(self.d)//self.p)

    def local_triviality_proof(self):
        omega=(0,1)
        w_minus_one=(-1,1)
        omega_times=mul(omega,w_minus_one,self.d)
        assert omega_times==(-order_parameter(self.d),0)
        assert self.p * self.overlap_inverse_numerator()==-order_parameter(self.d)
        # D(omega) and D(omega-1) cover since omega-(omega-1)=1.
        return {"cover_is_cover":True,
                "chart_U":"D(omega)",
                "chart_V":"D(omega-1)",
                "local_U_generator":"1",
                "local_V_generator":str(self.p),
                "transition_unit_only_on_overlap":self.p}


