    # The two local units satisfy u_U/u_V=81 in the overlap.
    assert norm(alpha,203)==3**4
    return {
        "cover":local,
        "one_cocycle_transition":3,
        "one_cocycle_nontrivial_by_norm_obstruction":True,
        "fourfold_transition":3**4,
        "fourfold_trivializer_global":alpha,
        "U_inverse_alpha_numerator":numerator_U,
        "V_alpha_over_81_numerator":numerator_V,
        "fourfold_transition_is_explicit_coboundary":True,
    }


