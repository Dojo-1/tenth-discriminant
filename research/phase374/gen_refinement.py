"""Phase374 deterministic Lean certificate generator.

Build the eight-arm eligibility table from the ORIGINAL Phase368 Python
selector, and separately transcribe the full manifest's native clocks and
arm attributes into a finite Lean predicate. The generated proof checks
their agreement over the complete relevant finite cost domain.

Do not alter the selector being tested. No signing or field proof occurs.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import sys

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
MANIFEST=ROOT/"research"/"phase368"/"manifest.json"
OUTPUT=ROOT/"lean"/"TenthDiscriminant"/"Phase374ManifestRefinement.lean"
PHASES=("fast","meso","review")
BOOLEANS=(False,True)
MAX_BUDGET=10  # Fin 10 covers 0..9; max current arm cost is 8


def literal(value):
    return "true" if value else "false"


def git_blob_sha(data: bytes) -> str:
    return hashlib.sha1(b"blob "+str(len(data)).encode()+b"\x00"+data).hexdigest()


def render(manifest: dict, raw: bytes) -> str:
    sys.path.insert(0,str(ROOT/"research"/"phase368"))
    from polybandit import PolyBandit
    arms=list(manifest["arms"])
    worldlets={w["id"]:w for w in manifest["worldlets"]}
    if len(arms)!=8 or {a["id"] for a in arms}!={a["id"] for a in manifest["arms"]}:
        raise ValueError("Phase374 pinned to exactly eight unique arms")
    if max(a["cost"] for a in arms)>=MAX_BUDGET:
        raise ValueError("Finite budget bound no longer saturates all arms")
    if set(x["id"] for x in manifest["clocks"])!=set(PHASES):
        raise ValueError("Research clock vocabulary has changed")
    if any(set(w["clocks"])-set(PHASES) for w in worldlets.values()):
        raise ValueError("Unexpected native clock")
    policy=PolyBandit(manifest)
    ids=[a["id"] for a in arms]
    lines=[
        "import TenthDiscriminant.Phase373ClockAuthoritySquare",
        "",
        "/-!",
        "Phase374 — manifest-derived finite eligibility refinement.",
        "Generated by research/phase374/gen_refinement.py.",
        "The finite Python oracle is the unchanged Phase368 PolyBandit.eligible.",
        "NOT a proof of arbitrary Python execution, trust, signature or field arithmetic.",
        "-/",
        "namespace TenthDiscriminant.Phase374",
        "open TenthDiscriminant.Phase373",
        "set_option autoImplicit false",
        "",
        f'def manifestBlobSha : String := "{git_blob_sha(raw)}"',
        f"def maxCertifiedBudget : Nat := {MAX_BUDGET-1}",
        "",
    ]
    def emit_match(name,typ,fn):
        lines.append(f"def {name} (a : Fin 8) : {typ} :=")
        lines.append("  match a.val with")
        for i,a in enumerate(arms):
            lines.append(f"  | {i} => {fn(a)}")
        lines.append(f"  | _ => {fn(arms[-1])}")
        lines.append("")
    emit_match("armName","String",lambda a:json.dumps(a["id"],ensure_ascii=True))
    emit_match("armCost","Nat",lambda a:str(a["cost"]))
    emit_match("nativeClocks","List ResearchClock",
               lambda a:"["+", ".join("."+c for c in worldlets[a["worldlet"]]["clocks"])+"]")
    emit_match("isHuman","Bool",lambda a:literal(a["execution"]=="human"))
    emit_match("isOriginal","Bool",lambda a:literal(a["source"]==manifest["frozen_source"]))
    emit_match("isContrast","Bool",lambda a:literal(a["purpose"]=="contrast"))
    emit_match("isForbidden","Bool",lambda a:literal(a["transport"]=="forbidden"))
    lines.extend([
        "/-- Total Boolean implementation of the Phase373 finite tier relation.",
        "The proof checks this executable clause against the Python oracle. -/",
        "def tierAdmitsBool (tier native : ResearchClock) : Bool :=",
        "  match tier, native with",
        "  | .fast, .fast => true",
        "  | .meso, .fast => true",
        "  | .meso, .meso => true",
        "  | .review, _ => true",
        "  | _, _ => false",
        "",
        "/-- Versioned, manifest-derived predicate. Cost is still a scalar",
        "RESOURCE BOUND, not an intelligence or mathematical truth score. -/",
        "def manifestEligible (a : Fin 8) (tier : ResearchClock) (budget : Nat)",
        "    (includeHuman includeContrast : Bool) : Bool :=",
        "  decide (armCost a <= budget) &&",
        "  !isForbidden a &&",
        "  (isOriginal a || (includeContrast && isContrast a)) &&",
        "  (includeHuman || !isHuman a) &&",
        "  (nativeClocks a).any (fun c => tierAdmitsBool tier c) &&",
        "  (!isHuman a || tier == .review)",
        "",
        "/-- Masks are computed using UNMODIFIED Phase368 PolyBandit.eligible",
        "on the original manifest, not by the Lean predicate above. -/",
        "def pythonOracleMask (tier : ResearchClock) (budget : Fin 10)",
        "    (includeHuman includeContrast : Bool) : Nat :=",
        "  match tier, includeHuman, includeContrast, budget.val with",
    ])
    for phase in PHASES:
        for human in BOOLEANS:
            for contrast in BOOLEANS:
                for budget in range(MAX_BUDGET):
                    observed={a.id for a in policy.eligible(
                        budget,include_human=human,phase=phase,include_contrast=contrast)}
                    mask=sum(1<<i for i,n in enumerate(ids) if n in observed)
                    lines.append(f"  | .{phase}, {literal(human)}, {literal(contrast)}, {budget} => {mask}")
    lines.extend([
        "  | _, _, _, _ => 0",
        "",
        "def oracleEligible (a : Fin 8) (tier : ResearchClock) (budget : Fin 10)",
        "    (includeHuman includeContrast : Bool) : Bool :=",
        "  decide ((pythonOracleMask tier budget includeHuman includeContrast /",
        "    (2 ^ a.val)) % 2 = 1)",
        "",
    ])
    for phase in PHASES:
        lines.extend([
            f"theorem exhaustive_{phase}_manifest_refinement :",
            "    forall a : Fin 8, forall b : Fin 10,",
            "      forall h c : Bool,",
            f"        manifestEligible a .{phase} b.val h c = oracleEligible a .{phase} b h c := by",
            "  decide",
            "",
        ])
    # Bridge the executable Boolean relation back to the Phase373 Prop,
    # and check the full manifest's four representative arms against
    # Phase373's independently authored finite policy projection.
    lines.extend([
        "theorem tier_relation_refines_phase373",
        "    (tier native : ResearchClock) :",
        "    tierAdmitsBool tier native = true \\u2194 TierAdmits tier native := by",
        "  cases tier <;> cases native <;> simp [tierAdmitsBool, TierAdmits]",
        "",
    ])
    sample=[
        ("source_anchor_mutation","sourceAnchor","meso","githubCI"),
        ("prolog_clock_counterworld","prologCounterworld","fast","githubCI"),
        ("lean_kernel_clock_rank","leanFormalization","meso","githubCI"),
        ("frame_clock_commuting_square","leanFormalization","meso","githubCI"),
        ("external_field_chart_reconstruction","externalReview","review","humanReview"),
    ]
    for idname, logical, native, plane in sample:
        i=ids.index(idname)
        theoremname="phase373_projection_"+idname
        lines.extend([
            f"theorem {theoremname} (tier : ResearchClock) :",
            f"    manifestEligible ({i} : Fin 8) tier 9 true false =",
            f"      decide (TierAuthorizable .{logical} tier .{native} .{plane}) := by",
            "  cases tier <;> decide",
            "",
        ])

    # Exact boundary witnesses, including a source contrast and native/tier asymmetry.
    i_source=ids.index("source_anchor_mutation")
    i_prolog=ids.index("prolog_clock_counterworld")
    i_contrast=ids.index("d203_worldlet_contrast")
    lines.extend([
        "theorem source_not_fast :",
        f"    manifestEligible ({i_source} : Fin 8) .fast 9 true false = false := by decide",
        "theorem fast_prolog_allowed_in_meso :",
        f"    manifestEligible ({i_prolog} : Fin 8) .meso 9 true false = true := by decide",
        "theorem d203_contrast_requires_opt_in :",
        f"    manifestEligible ({i_contrast} : Fin 8) .meso 9 true false = false /\\",
        f"    manifestEligible ({i_contrast} : Fin 8) .meso 9 true true = true := by decide",
        "",
        "end TenthDiscriminant.Phase374",
        "",
        "#print axioms TenthDiscriminant.Phase374.exhaustive_fast_manifest_refinement",
        "#print axioms TenthDiscriminant.Phase374.exhaustive_meso_manifest_refinement",
        "#print axioms TenthDiscriminant.Phase374.exhaustive_review_manifest_refinement",
        "",
    ])
    return "\n".join(lines)


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--check",action="store_true")
    args=p.parse_args()
    raw=MANIFEST.read_bytes()
    expected=render(json.loads(raw),raw)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8")!=expected:
            raise SystemExit("STALE_PHASE374_CERTIFICATE: manifest/selector/Lean table changed")
        print("PHASE374_CERTIFICATE_SOURCE_MATCH: all 8 arms, 3 phases, 2 flags, budgets 0..9")
    else:
        OUTPUT.write_text(expected,encoding="utf-8")
        print(f"generated {OUTPUT}, {len(expected)} characters")


if __name__=="__main__":
    main()
