#!/usr/bin/env python3
"""Exact finite minimum-cardinality certificate for the original D=19 jet image.

Works on the entire 21-node ellipse: the common HNF basis converts the image
question to surjectivity over Z. A 5-node image generator would remain
surjective mod 2, so exhaustive rank deficiency mod 2 excludes all 5-node sets.
One explicitly given 6-node set has the same full integer HNF, proving the
minimum is exactly six for this frozen 32-row ordinary-jet system.
"""
from __future__ import annotations
from collections import Counter
from itertools import combinations
from math import log
from phase144_verifier import FULL, FOUR, evaluation, lattice, gram_det, val

SIX=[(-2,-1),(-1,-1),(-1,0),(0,-1),(0,0),(1,-1)]
assert all(q in FULL for q in SIX) and set(FOUR).issubset(SIX)


def rank_binary(columns):
    basis=[0]*32
    rank=0
    for vec in columns:
        while vec:
            i=vec.bit_length()-1
            if basis[i]:
                vec ^= basis[i]
            else:
                basis[i]=vec
                rank+=1
                break
    return rank


def main():
    E=evaluation(FULL)
    D=abs(int(evaluation(FOUR).det(method='domain-ge')))
    H,d=lattice(E,D)
    # Every original column belongs to the integer column image generated by H.
    T=H.inv()*E
    assert all(entry.q==1 for entry in T)
    blocks=[]
    for node in range(len(FULL)):
        blocks.append([sum((int(T[i,8*node+j])%2)<<i for i in range(32))
                       for j in range(8)])
    assert rank_binary([v for block in blocks for v in block])==32
    histogram=Counter()
    for choice in combinations(range(len(FULL)),5):
        vectors=[v for node in choice for v in blocks[node]]
        histogram[rank_binary(vectors)]+=1
    assert sum(histogram.values())==20349
    assert max(histogram)==28  # Hence no five (or fewer) points generate im(E).

    E6=evaluation(SIX)
    H6,d6=lattice(E6,D)  # The same four-node witness is still present.
    assert H6==H and d6==d
    G6=gram_det(E6)
    assert G6>0 and G6%d6**2==0
    assert val(G6,3)==39
    Gfull=gram_det(E)
    assert G6<Gfull
    print('All C(21,5)=20,349 five-node configurations fail mod-2 surjectivity.')
    print('Binary-rank histogram:',dict(sorted(histogram.items())))
    print('Maximum 5-node binary rank:',max(histogram))
    print('Six-point exact witness:',SIX)
    print('Image HNF equal:',H6==H,'index:',d6)
    print('log det full/six:',f'{log(Gfull):.12f}',f'{log(G6):.12f}')
    print('PASS: finite minimum integral-image support size = 6 (no general theorem).')

if __name__=='__main__':main()
